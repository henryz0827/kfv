"""Turn results/*.json into results/RESULTS.md. Every number in the README comes from this file's output.

    python -m kfv.report
"""
import json

from .study import RESULTS


def load(name):
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def ledger_table(rows, label):
    out = [f"| {label} | contracts (M) | share | taker result before fees (c/contract) | s.e. | fee (c/contract) | after fees |",
           "|---|---:|---:|---:|---:|---:|---:|"]
    total = sum(r["contracts"] for r in rows.values())
    for k, r in rows.items():
        out.append(f"| {k} | {r['contracts'] / 1e6:.1f} | {100 * r['contracts'] / total:.0f}% | {r['gross_per_contract_c']:+.2f} | "
                   f"{r['se_c']:.2f} | {r['fee_per_contract_c']:.2f} | {r['gross_per_contract_c'] - r['fee_per_contract_c']:+.2f} |")
    return "\n".join(out)


def main():
    led, imp, dev, fin = load("ledger"), load("implied"), load("dev"), load("final")
    md = ["# Results", "", "Generated by `python -m kfv.report` from `results/*.json`. Standard errors treat a whole hourly event as one draw.", ""]
    if led:
        a, s = led["all"], led["sample"]
        scale = s["series_contracts"] / a["contracts"]
        md += ["## T1. Who pays whom: the ledger of trade prints", "",
               f"Sample: every fifth hourly event, {s['events']} events from {s['first']} to {s['last']} UTC, "
               f"{a['trades']:,} trades and {a['contracts'] / 1e6:.1f}M contracts "
               f"({100 / scale:.0f}% of the series' {s['series_contracts'] / 1e6:,.0f}M contracts in {s['series_events']:,} events).", "",
               f"- Takers paid ${a['premium'] / 1e6:.1f}M in premium and made {'+' if a['gross'] > 0 else '-'}${abs(a['gross']) / 1e6:.2f}M at settlement before fees, "
               f"which is {a['gross_per_contract_c']:+.3f}c a contract (s.e. {a['se_c']:.3f}). Makers made the other side of that.",
               f"- Taker fees at the schedule were ${a['fees'] / 1e6:.2f}M, {a['fee_per_contract_c']:.2f}c a contract, so takers ended at "
               f"{a['gross_per_contract_c'] - a['fee_per_contract_c']:+.2f}c a contract after fees.",
               f"- Scaled to the whole series over the two months: about ${a['fees'] * scale / 1e6:.0f}M of taker fees. Makers' side of the ledger, "
               f"before their own costs, scales to {'-' if a['gross'] > 0 else '+'}${abs(a['gross']) * scale / 1e6:.1f}M with a standard error of "
               f"${a['se_c'] / 100 * s['series_contracts'] / 1e6:.1f}M, which is level.",
               "- In every sampled event the trade sizes add up to the volume the exchange reports for the event.", "",
               ledger_table(led["sides"], "taker bought"), "", ledger_table(led["by_price"], "price the taker paid"), "",
               ledger_table(led["by_time"], "time to the close"), ""]
        mo = led["markouts"]
        md += [f"Quote-based measures on the {100 * mo['coverage']:.0f}% of contracts traded with a two-sided quote within 10c on both sides of the trade "
               "(spread paid = trade price against the mid at the start of the trade's minute, a cost to the taker; markout = the mid one to two "
               "minutes later against the trade price, in the taker's favour when positive):", "",
               "| | contracts (M) | spread paid (c/contract) | s.e. | markout (c/contract) | s.e. | fee (c/contract) |", "|---|---:|---:|---:|---:|---:|---:|"]
        for k, r in [("all trades", mo["all"])] + list(mo["by_time"].items()):
            md.append(f"| {k} | {r['contracts'] / 1e6:.1f} | {r['spread_paid_c']:.2f} | {r['spread_se_c']:.2f} | {r['markout_c']:+.2f} | "
                      f"{r['markout_se_c']:.2f} | {r['fee_c']:.2f} |")
        md.append("")
        c = led["taker_side_check"]
        md += [f"Direction check: of {c['matched_trades']:,} trades matched to the quote one minute earlier, "
               f"{100 * c['yes_takers_above_prior_mid']:.0f}% of YES-taker prints were above that mid and "
               f"{100 * c['no_takers_below_prior_mid']:.0f}% of NO-taker prints were below it.", ""]
    if imp:
        sn = imp["snapshots"]
        md += ["## T2. What the ladder implies, against what happened", "",
               f"{sn['rows']:,} quotes with a two-sided market in {sn['events']:,} events; mean half-spread {sn['half_spread_c']:.2f}c. "
               "A ladder fit is the least-squares line through the probit of the mids against log strike.", "",
               "| minutes to close | ladders | strikes per fit | implied / realized variance (1-min returns) | 95% interval | implied / squared move to settlement | 95% interval | trailing-24h model / realized |",
               "|---|---:|---:|---:|---|---:|---|---:|"]
        for h, r in imp["implied_vs_realized"].items():
            md.append(f"| {h} | {r['ladders']:,} | {r['strikes_per_fit']:.1f} | {r['implied_over_realized_var']:.2f} | "
                      f"{r['ci'][0]:.2f} to {r['ci'][1]:.2f} | {r['implied_over_move_var']:.2f} | {r['move_ci'][0]:.2f} to {r['move_ci'][1]:.2f} | "
                      f"{r['model_over_realized_var']:.2f} |")
        md += ["", "The hour's move from the implied level to settlement, in implied standard deviations (a normal gives variance 1, "
               "kurtosis 3, 38.3% inside a half, 4.6% beyond two, 0.27% beyond three):", "",
               "| minutes to close | variance | kurtosis | inside 0.5 | beyond 2 | beyond 3 | implied level minus Coinbase spot, median ($) | median abs. ($) |",
               "|---|---:|---:|---:|---:|---:|---:|---:|"]
        for h, r in imp["implied_vs_realized"].items():
            md.append(f"| {h} | {r['z_var']:.2f} | {r['z_kurtosis']:.1f} | {100 * r['z_inside_half']:.1f}% | {100 * r['z_beyond_two']:.1f}% | "
                      f"{100 * r['z_beyond_three']:.2f}% | {r['level_minus_spot_median']:+.1f} | {r['level_minus_spot_mad']:.1f} |")
        i_ = imp["information"]
        md += ["", f"Calibration of the quoted mid, all snapshots: probit coefficient {i_['coef_market']:.3f} (s.e. {i_['se_market']:.3f}, "
               f"{i_['rows']:,} quotes in {i_['events']:,} events); 1 is calibrated, above 1 means prices sit too close to 50c.", "",
               "| quoted mid | quotes | mean mid (c) | paid (%) | paid minus mid (c) | s.e. |", "|---|---:|---:|---:|---:|---:|"]
        for k, r in imp["calibration"].items():
            md.append(f"| {k} | {r['quotes']:,} | {r['mid_c']:.1f} | {r['paid_pct']:.1f} | {r['diff_c']:+.2f} | {r['se_c']:.2f} |")
        md.append("")
    cv = load("cross_venue")
    if cv:
        r, f, l = cv["repriced"], cv["fixings"], cv["listed"]
        md += ["## Kalshi against Polymarket, same strike at noon Eastern", "",
               f"- Same strike, same minute, Kalshi mid between 5c and 95c: {cv['live_pairs']} pairs on {cv['days']} days. Polymarket minus Kalshi "
               f"averaged {cv['mean_gap_c']:+.1f}c (s.e. {cv['se_gap_c']:.1f}); mean absolute gap {cv['mean_abs_gap_c']:.1f}c, median {cv['median_abs_gap_c']:.1f}c. "
               f"Crossing on Kalshi costs {cv['mean_kalshi_cost_c']:.1f}c (half-spread plus fee).",
               f"- Repriced onto Polymarket's fixing with the Kalshi ladder's own implied volatility ({r['pairs']} pairs with a ladder fit): Binance sat a median "
               f"${r['binance_minus_implied_level_median']:.0f} above the ladder's implied index level, and the average gap of {r['mean_gap_c']:+.1f}c "
               f"(s.e. {r['se_gap_c']:.1f}) falls to {r['mean_resid_c']:+.1f}c (s.e. {r['se_resid_c']:.1f}). The mean absolute gap stays at {r['mean_abs_resid_c']:.1f}c: "
               "the two price series are sampled up to two minutes apart.",
               f"- The two fixings over {f['days']} days: Binance's 12:00 candle close minus Kalshi's settlement value had median ${f['median_diff']:+.0f}, "
               f"median absolute ${f['median_abs_diff']:.0f}, 90th percentile ${f['p90_abs_diff']:.0f}, maximum ${f['max_abs_diff']:.0f}. Against the last Binance "
               f"trade before 12:00:00 the median is ${f['median_diff_same_minute']:+.0f}.",
               f"- On {f['days_with_a_split_100_strike']} of {f['days']} days at least one of Kalshi's $100 strikes would have resolved the other way on Polymarket's "
               f"fixing ({f['strikes_split']} strikes in all). Of {l['matched_strikes']} strikes actually listed on both venues, {l['resolved_differently']} resolved differently:"]
        md += [f"  - {c['date']}, ${c['strike']:,.0f}: Polymarket {'Yes' if c['polymarket_yes'] else 'No'} (Binance close {c['binance_close']:,.2f}), "
               f"Kalshi {'Yes' if c['kalshi_yes'] else 'No'} (index average {c['kalshi_settlement']:,.2f})." for c in l["cases"]]
        md.append("")
    for name, res in (("Development window", dev), ("Final window (run once)", fin)):
        if not res:
            continue
        md += [f"## T3 and T4. {name}: {res['window']['first']} to {res['window']['last']} UTC", "",
               "| minutes to close | quotes | events | coef. on market probit | coef. on (model - market) | t | Brier market | Brier model | mean abs. gap (c) | half-spread (c) |",
               "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for h, r in res["information"].items():
            md.append(f"| {h} | {r['rows']:,} | {r['events']:,} | {r['coef_market']:.2f} | {r['coef_model_gap']:+.2f} | {r['t_model_gap']:+.1f} | "
                      f"{r['brier_market']:.4f} | {r['brier_model']:.4f} | {r['mean_abs_gap_c']:.1f} | {r['half_spread_c']:.1f} |")
        md += ["", "| minutes to close | orders | buy YES | buy NO | before fees (c/contract) | fee | after fees (c/contract) | s.e. | t |",
               "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for h, r in res["taker_rule"].items():
            if r["orders"] < 2:
                md.append(f"| {h} | {r['orders']} | | | | | | | |")
                continue
            md.append(f"| {h} | {r['orders']:,} | {r['buy_yes']:,} | {r['buy_no']:,} | {r['gross_per_contract_c']:+.2f} | {r['fee_per_contract_c']:.2f} | "
                      f"{r['net_per_contract_c']:+.2f} | {r['se_c']:.2f} | {r['t']:+.1f} |")
        md.append("")
        if "vol_sensitivity" in res:
            md += ["Volatility window sensitivity (development window only, all horizons):", "",
                   "| trailing minutes | coef. on (model - market) | t | Brier model | rule orders | rule after fees (c/contract) | t |", "|---|---:|---:|---:|---:|---:|---:|"]
            for k, r in res["vol_sensitivity"].items():
                i, t = r["information"], r["taker_rule"]
                md.append(f"| {k} | {i['coef_model_gap']:+.2f} | {i['t_model_gap']:+.1f} | {i['brier_model']:.4f} | {t['orders']:,} | "
                          f"{t.get('net_per_contract_c', float('nan')):+.2f} | {t.get('t', float('nan')):+.1f} |")
            md.append("")
    (RESULTS / "RESULTS.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
